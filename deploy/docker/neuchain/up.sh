#!/usr/bin/env bash
# NeuChain deploy - PHASE 4 (partial: build + topology scaffolding in place, the
# adapter and the exact run flags are still TODO - see
# docs/platforms/neuchain-client-implementation.md).
#
#   ./up.sh [profile]
#
# Steps:
#   1. build bench/neuchain-build:ev (Ubuntu 20.04 toolchain) if absent
#   2. build bench/neuchain:ev runtime image if absent
#   3. bring up 4 block servers + 1 epoch server with profile resource limits
#   4. emit connection.env
source "$(dirname "${BASH_SOURCE[0]}")/../lib.sh"
need docker
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

NEUCHAIN_REF="${NEUCHAIN_REF:-ev}"

if ! docker image inspect "bench/neuchain:${NEUCHAIN_REF}" >/dev/null 2>&1; then
  die "image bench/neuchain:${NEUCHAIN_REF} missing - run deploy/docker/neuchain/build.sh first (slow: ~1h, builds ~15 C++ deps from source)"
fi

# Resource limits from the profile.
BENCH_NC_CPUS="$(platform_field neuchain per_container.cpus   || echo 1.2)"
BENCH_NC_MEM="$(platform_field neuchain per_container.memory   || echo 1g)"
export BENCH_NC_CPUS BENCH_NC_MEM

warn "NeuChain run flags / config files in docker-compose.yml are PLACEHOLDERS."
warn "Fill them in from the iDC-NEU/NeuChain@ev repo before expecting a working network."

drop_caches
docker compose up -d

cat > "${HERE}/connection.env" <<EOF
# generated by deploy/docker/neuchain/up.sh  ($(date -u +%FT%TZ))
# NeuChain block servers SUB on :5001 (submit) and REP on :7003 (query).
# PLACEHOLDER host ports - align with docker-compose.yml once the run flags are set.
BENCH_ADAPTER_BLOCK_SERVERS=localhost:5001,localhost:5011,localhost:5021,localhost:5031
BENCH_ADAPTER_QUERY_ENDPOINT=localhost:7003
BENCH_ADAPTER_USER_PRIV_KEY_PATH=${HERE}/.cache/crypto/user_0.pri
BENCH_ADAPTER_USER_PUB_KEY_PATH=${HERE}/.cache/crypto/user_0.pub
BENCH_ADAPTER_FUNC_NAME=ycsb
BENCH_ADAPTER_TABLE_NAME=test_table
BENCH_PLATFORM_VERSION=neuchain-${NEUCHAIN_REF}
EOF
log "neuchain containers up (topology scaffolding; adapter is pure-Go, ZMQ+protobuf)"
log "user RSA keys: run './user -b 1 1 1' with the crypto config inside the build image and copy them to .cache/crypto/"
